import { SuggestionTypes, Speakers, type Speaker, type SuggestionType, type InfoCard } from "@/features/calls/interfaces/calls.interfaces";
import { ScriptStageTypes, type ScriptStage } from "@/features/assistant-agents/interfaces/assistant-agents.interfaces";
import rawLines from "./demo-lines.json";

export interface DemoLine {
  id: string;
  speaker: Speaker;
  text: string;
  audio: string;
}

export interface DemoSuggestion {
  type: SuggestionType;
  text: string;
  reason: string;
  alternatives?: string[];
  infoCard?: InfoCard;
  // How long the co-pilot shows "Thinking…" before this card appears.
  thinkMs: number;
}

export interface DemoBeat {
  line: DemoLine;
  // Co-pilot cards that appear once this line has finished, in order.
  suggestions?: DemoSuggestion[];
  // Script stages the seller has covered by the end of this line.
  completes?: string[];
  // Pause after the line (and its cards) before the next one starts: the seller reads the card.
  pauseMs: number;
}

export const DEMO_AGENT_NAME = "Loopwise sales co-pilot";
export const DEMO_PROSPECT = "Dana";
export const DEMO_TITLE = "Loopwise · Dana Whitfield";

// Pre-recorded audio generated by `npm run demo:audio`. When a file is missing the browser's speech synthesis is used.
const LINES = (rawLines as { id: string; speaker: string; text: string }[]).map<DemoLine>((item) => ({
  id: item.id,
  speaker: item.speaker === "USER" ? Speakers.USER : Speakers.PROSPECT,
  text: item.text,
  audio: `/demo/line-${item.id}.mp3`,
}));

const line = (id: string): DemoLine => {
  const found = LINES.find((item) => item.id === id);
  if (!found) throw new Error(`Unknown demo line ${id}`);
  return found;
};

