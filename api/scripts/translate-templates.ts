/* One-off generator: translates the English template texts into every supported call language.
   Usage: npm run translate:templates [-- el,es]   (needs OPENAI_API_KEY, e.g. via .env.staging) */
import { mkdirSync, writeFileSync } from 'fs';
import { join } from 'path';
import { SUPPORTED_LANGUAGES } from '../src/shared/config/languages/languages.config';
import { extractSourceTexts } from '../src/shared/config/templates/i18n/template-translation';

const MODEL = 'gpt-4.1';
const OUT_DIR = join(__dirname, '../src/shared/config/templates/i18n');

const SYSTEM = (language: string) =>
  `You localise sales-call template content into ${language} for native speakers. Return ONLY a JSON object with exactly the same keys, nesting and array lengths as the input; translate every string value. Rules: keep {placeholders} in curly braces unchanged and untranslated; keep numbers and times; write natural, spoken, idiomatic ${language} (not literal); for prospect_name use a common ${language}-speaking-country name, for company a plausible local company name, and accent MUST be a native regional accent of ${language}-speaking people, written in ${language} (never an English-language accent such as American or British; keep an empty string empty); briefing/background_story must use the localised prospect_name and company consistently.`;

async function translate(language: string, payload: unknown) {
  const response = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${process.env.OPENAI_API_KEY}`,
    },
    body: JSON.stringify({
      model: MODEL,
      temperature: 0.3,
      response_format: { type: 'json_object' },
      messages: [
        { role: 'system', content: SYSTEM(language) },
        { role: 'user', content: JSON.stringify(payload) },
      ],
    }),
  });
  if (!response.ok) throw new Error(`${response.status} ${await response.text()}`);
  const data = await response.json();
  return JSON.parse(data.choices[0].message.content);
}

// Same keys and array lengths as the source, so index-based merging at runtime is safe.
function assertSameShape(source: any, translated: any, path = ''): void {
  if (Array.isArray(source)) {
    if (!Array.isArray(translated) || translated.length !== source.length)
      throw new Error(`Shape mismatch at ${path}`);
    source.forEach((s, i) => assertSameShape(s, translated[i], `${path}[${i}]`));
  } else if (source && typeof source === 'object') {
    for (const key of Object.keys(source)) {
      if (!(key in (translated ?? {}))) throw new Error(`Missing ${path}.${key}`);
      assertSameShape(source[key], translated[key], `${path}.${key}`);
    }
  } else if (typeof translated !== typeof source) {
    throw new Error(`Type mismatch at ${path}`);
  }
}

async function main() {
  if (!process.env.OPENAI_API_KEY) throw new Error('OPENAI_API_KEY is not set');
  const only = process.argv[2]?.split(',');
  const source = extractSourceTexts();
  mkdirSync(OUT_DIR, { recursive: true });

  for (const { code, name } of SUPPORTED_LANGUAGES) {
    if (code === 'en' || (only && !only.includes(code))) continue;
    console.log(`Translating to ${name} (${code})…`);
    const [assistant, practice, rest] = await Promise.all([
      translate(name, source.assistant),
      translate(name, source.practice),
      translate(name, { criteria: source.criteria, consent_line: source.consent_line }),
    ]);
    const result = { assistant, practice, ...rest };
    assertSameShape(source, result);
    writeFileSync(
      join(OUT_DIR, `${code}.ts`),
      `// Generated by scripts/translate-templates.ts, edit freely.\nimport { TemplateTranslation } from './template-translation';\n\nconst ${code}: TemplateTranslation = ${JSON.stringify(result, null, 2)};\n\nexport default ${code};\n`,
    );
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
